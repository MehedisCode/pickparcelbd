        Route::get('cash-memos/{id}', [CashMemoController::class, 'show']);
        Route::post('cash-memos/{id}/documents', [CashMemoController::class, 'upload']);
        Route::post('cash-memos/{id}/send', [CashMemoController::class, 'send']);
        Route::delete('documents/{id}', [CashMemoController::class, 'destroyDocument']);
        Route::get('documents/{id}', [CashMemoController::class, 'document']);
        Route::get('parcels', [ParcelController::class, 'index']);
        Route::post('parcels', [ParcelController::class, 'store']);
        Route::post('parcels/assign', [ParcelController::class, 'assign']);
        Route::post('parcels/cancel-assignments', [ParcelController::class, 'cancelBatch']);
        Route::post('parcels/pickup-batch', [ParcelController::class, 'pickupBatch'])->middleware('throttle:verification');
        Route::get('parcels/{code}', [ParcelController::class, 'show']);
        Route::get('parcels/{code}/codes', [ParcelController::class, 'codes'])->middleware('throttle:verification');
