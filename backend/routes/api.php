        Route::patch('account', [AccountController::class, 'update']);
        Route::post('account/location', [AccountController::class, 'location']);
        Route::post('account/reverse-geocode', [AccountController::class, 'reverseGeocode'])->middleware('throttle:5,1');
        Route::post('account/heartbeat', [AccountController::class, 'heartbeat']);
        Route::post('account/terms', [AccountController::class, 'terms']);
        Route::get('members', [AccountController::class, 'members']);
        Route::get('people', [SocialController::class, 'people']);
