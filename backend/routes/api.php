            Route::post('recovery', [AdminController::class, 'recovery']);
            Route::patch('rates', [AdminController::class, 'rates']);
            Route::get('finance', [FinanceController::class, 'index']);
            Route::put('commission-rules', [FinanceController::class, 'rule']);
            Route::post('settlements', [FinanceController::class, 'settle']);
            Route::post('finance/{code}/recovery/{action}', [FinanceController::class, 'repair'])->whereIn('action', ['repair-member-credit', 'reconcile-delivery', 'repair-return', 'repair-return-request']);
            Route::post('finance/{code}/{action}', [FinanceController::class, 'command'])->whereIn('action', ['receive-collection', 'confirm-wallet', 'receive-return', 'calculate-commission']);
        });
    });
});
