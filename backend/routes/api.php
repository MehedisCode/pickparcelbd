        Route::post('notifications/read', [CommunicationController::class, 'readNotifications']);
        Route::post('device-tokens', [CommunicationController::class, 'token']);
        Route::get('following', [SocialController::class, 'follows']);
        Route::post('profiles/{id}/follow', [SocialController::class, 'follow']);
        Route::post('profiles/{id}/comments', [SocialController::class, 'comment']);
        Route::post('profiles/{id}/share', [SocialController::class, 'share']);
        Route::get('buyer-blocks', [SocialController::class, 'blocks']);
        Route::post('buyer-blocks/{id}', [SocialController::class, 'block']);
        Route::delete('buyer-blocks/{id}', [SocialController::class, 'unblock']);
