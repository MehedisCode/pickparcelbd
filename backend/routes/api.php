        Route::get('transfers', [TransferController::class, 'index']);
        Route::post('transfers', [TransferController::class, 'store']);
        Route::post('transfers/preview', [TransferController::class, 'preview']);
        Route::post('transfers/accept', [TransferController::class, 'accept']);
        Route::get('transfers/{id}', [TransferController::class, 'show'])->whereNumber('id');
        Route::get('transfers/{id}/export', [TransferController::class, 'export']);
        Route::post('transfers/{id}/collection-handover', [TransferController::class, 'handover']);
